const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const watchdog = setTimeout(() => process.exit(2), 120000);
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const out = process.argv[2];
  if (out) fs.mkdirSync(out, { recursive: true });
  try {
    const { summarizeTrade, sortTradeCountries } = await import('../lib/trade.ts');
    const data = JSON.parse(fs.readFileSync('data/trade/dram.json', 'utf8'));
    for (const width of [1440, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } });
      page.setDefaultTimeout(15000);
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto('http://localhost:3000/trade');
      await page.locator('.trade-map[data-ready="true"]').waitFor({ timeout: 45000 });
      await page.getByLabel('기업 비교 지표').selectOption('price');
      assert.equal(await page.locator('[data-overlay-series]').count(), 2);
      assert((await page.locator('[data-overlay-value]').count()) > 40);
      await page.getByLabel('수출 대상국').selectOption('CN');
      assert.equal(await page.getByTestId('trend-country').innerText(), '중국');
      const row = data.rows.find(r => r.month === '2026-07' && r.country === 'CN');
      assert.equal(Number(await page.locator('[data-export-value]').last().getAttribute('data-export-value')), row.usd);
      await page.getByLabel('차트 지표').selectOption('usdPerKg');
      assert.equal(Number(await page.locator('[data-export-value]').last().getAttribute('data-export-value')), row.usd / row.kg);
      await page.getByLabel('삼성전자', { exact: true }).uncheck();
      assert.equal(await page.locator('[data-overlay-series]').count(), 1);
      if (out) await page.locator('.trade-analysis-grid').screenshot({ path: out + '/price-' + width + '.png' });
      await page.getByLabel('기업 비교 지표').selectOption('revenue');
      await page.getByLabel('삼성전자', { exact: true }).check();
      assert.equal(await page.locator('[data-overlay-series]').count(), 2);
      assert((await page.locator('[data-overlay-value]').count()) >= 14);
      await page.locator('.trend-hit-targets button').filter({ hasText: '' }).nth(22).focus();
      assert.match(await page.locator('.trend-readout').innerText(), /공시/);
      if (out) await page.locator('.trade-analysis-grid').screenshot({ path: out + '/revenue-' + width + '.png' });
      await page.getByLabel('수출 대상국').selectOption('NL');
      await page.getByLabel('기업 비교 지표').selectOption('none');
      await page.getByLabel('차트 지표').selectOption('value');
      await page.getByRole('button', { name: '12개월', exact: true }).click();
      const latest = data.rows.find(r => r.month === '2026-07' && r.country === 'NL');
      const previous = data.rows.find(r => r.month === '2026-06' && r.country === 'NL');
      const dot = page.locator('.trend-mom-point[data-month="2026-07"]');
      assert(Math.abs(Number(await dot.getAttribute('data-change')) - (latest.usd / previous.usd - 1) * 100) < 1e-8);
      await page.locator('.trend-hit-targets button').last().focus();
      assert.match(await page.locator('.trend-change-readout').innerText(), /전월 대비 \+/);
      if (out) await page.locator('.trade-analysis-grid').screenshot({ path: out + '/mom-dots-' + width + '.png' });
      await page.getByLabel('전월 대비 (%)', { exact: true }).uncheck();
      assert.equal(await page.locator('.trend-mom-point').count(), 0);
      await page.getByLabel('전월 대비 (%)', { exact: true }).check();
      await page.getByLabel('차트 지표').selectOption('usdPerKg');
      assert(Math.abs(Number(await dot.getAttribute('data-change')) - ((latest.usd / latest.kg) / (previous.usd / previous.kg) - 1) * 100) < 1e-8);
      const mom = page.getByRole('columnheader').filter({ has: page.getByRole('button', { name: 'MoM', exact: true }) });
      await page.getByRole('button', { name: 'MoM', exact: true }).click();
      assert.equal(await mom.getAttribute('aria-sort'), 'descending');
      const expected = sortTradeCountries(summarizeTrade(data, '2026-07').countries.filter(c => c.usd > 0), 'mom', 'desc');
      assert.equal(await page.locator('.trade-country-table tbody tr').first().locator('td').first().innerText(), expected[0].name);
      await page.getByRole('button', { name: 'MoM', exact: true }).click();
      assert.equal(await mom.getAttribute('aria-sort'), 'ascending');
      await page.getByRole('button', { name: '비중 변화', exact: true }).click();
      assert.match(await page.locator('.trade-country-table tbody').innerText(), /%p/);
      await page.getByRole('button', { name: '수출 통계 업데이트 알림', exact: true }).click();
      await page.getByRole('region', { name: '수출 통계 업데이트 목록' }).waitFor();
      assert.equal(await page.locator('.trade-notification-panel li').count(), 3);
      if (out) await page.screenshot({ path: out + '/notifications-' + width + '.png' });
      await page.getByRole('button', { name: '모두 읽음', exact: true }).click();
      assert.equal(await page.locator('.trade-notification-count').count(), 0);
      await page.reload();
      await page.locator('.trade-map[data-ready="true"]').waitFor();
      assert.equal(await page.locator('.trade-notification-count').count(), 0);
      const updates = await (await page.request.get('http://localhost:3000/api/trade/updates')).json();
      updates.updates[0].id += ':test-revision';
      await page.route('**/api/trade/updates', route => route.fulfill({ json: updates }));
      await page.reload();
      await page.locator('.trade-map[data-ready="true"]').waitFor();
      assert.equal(await page.locator('.trade-notification-count').innerText(), '1');
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      assert.deepEqual(errors, []);
      console.log(JSON.stringify({ width, priceOverlay: true, quarterlyOverlay: true, countryUsdPerKg: true, momSort: true, readState: true, newRevisionBadge: true, errors }));
      await page.close();
    }
  } finally { await browser.close(); clearTimeout(watchdog); }
})().catch(error => { console.error(error); process.exit(1); });
